//used for ship movement
unsigned int blankSprite[16 * 16];
void createBlankSprite() {
    for (int i = 0; i < 256; i++) {
        blankSprite[i] = 0x1840; // very dark navy
    }
}





void drawSprite(const unsigned int *sprite, int x, int y, int currWidth, int currHeight) {
    //X address space
    sendCommand(0x2A); //CASET
    sendData(x >> 8); //16 bits are sent, so send first upper bits 
    sendData(x & 0xFF); //send 2nd lower bits, DO SAME FOR Y 
    sendData((x + currWidth - 1) >> 8);  //0-127, minus 1 for corrext index
    sendData((x + currWidth - 1) & 0xFF);
    //Y address space 
    sendCommand(0x2B); //RASET
    sendData(y >> 8); 
    sendData(y & 0xFF);
    sendData((y + currHeight - 1) >> 8); 
    sendData((y + currHeight - 1) & 0xFF);
    
    sendCommand(0x2C); 
    for (int i = 0; i < currWidth * currHeight; i++) {
        sendData(sprite[i] >> 8);   
        sendData(sprite[i] & 0xFF);
    }
}

